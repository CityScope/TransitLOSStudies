"""flex/FIT_RESULTS.md from the results of fit_tests.py (called as `fit_tests.py report`)."""
from __future__ import annotations

import json
from pathlib import Path

FIT = ["boston", "san_francisco", "toronto", "concepcion", "guadalajara"]
SMALL = ["beerseba", "gipuzkoa", "taipei", "hamburg", "andorra"]
NAMES = {"boston": "Boston", "san_francisco": "San Francisco", "toronto": "Toronto", "concepcion": "Concepción", "guadalajara": "Guadalajara",
         "beerseba": "Beersheba", "gipuzkoa": "Gipuzkoa", "taipei": "Taipei", "hamburg": "Hamburg", "andorra": "Andorra", "us": "US final fit"}


def _j(out: Path, name):
    f = out / f"{name}.json"
    return json.loads(f.read_text()) if f.is_file() else None


def _f(x, nd=3):
    return "–" if x is None else f"{x:.{nd}f}"


def _row(label, vals):
    return f"| {label} | " + " | ".join(vals) + " |"


def _head(cols):
    return "| | " + " | ".join(cols) + " |\n|---|" + "---:|" * len(cols)


def write(out: Path) -> Path:
    L = ["# City science flex fits: results", "",
         "Generated by `flex/fit_tests.py report` from `flex/results/`. Model, rules and tests: `flex/fit_tests.py` and "
         "`tools/studytools/flexfit.py` (the final US form, speed curve fitted first and frozen, then the mode factors).", "",
         "Every number is held out. **Skill** = 1 − loss / loss of the city's own constant share (beta-binomial per person); **R²** = share "
         "of the variance of the units' transit share (transit ÷ (transit + car)) explained, people-weighted. Each city always has its own "
         "level (the scale factor), fitted on its own units.", ""]
    cols = [NAMES[c] for c in FIT]

    us = _j(out, "us")
    if us:
        L += ["## 1. The US curves and the map's default score on the cities", "", "Within-city 5-fold held out; only each city's level and "
              "dispersion fitted (+ eps where said).", "", _head(cols + ["mean"])]
        for k, lab in (("us_level", "US final curves, level"), ("us_level_eps", "US final curves, level + eps"),
                       ("default_level_eps", "map default score, level + eps")):
            r = us[k]
            L.append(_row(lab + " — R²", [_f(r["r2"][c]) for c in FIT] + [_f(r["r2_mean"])]))
            L.append(_row(lab + " — skill", [_f(r["skill"][c], 4) for c in FIT] + [_f(r["mean"], 4)]))
        L.append("")

    own = {c: _j(out, f"own_{c}") for c in FIT}
    if any(own.values()):
        L += ["## 2. Each city fitted on its own", "", _head(cols)]
        L.append(_row("held-out R²", [_f(own[c]["cv"]["r2"][c]) if own[c] else "–" for c in FIT]))
        L.append(_row("held-out skill", [_f(own[c]["cv"]["skill"][c], 4) if own[c] else "–" for c in FIT]))
        for k, lab, nd in (("h50_min", "headway at half value (min)", 1), ("kh", "headway slope", 2), ("w50_m", "walk half distance (m)", 0),
                           ("kw", "walk slope", 2), ("c_h", "walk slope x log(h / 10 min)", 2), ("c_v", "walk slope x log(v / 20 km/h)", 2),
                           ("eps", "eps", 4)):
            L.append(_row(lab, [_f(own[c]["params"][k], nd) if own[c] else "–" for c in FIT]))
        for mo in ("bus", "tram"):
            L.append(_row(f"mode factor {mo} (rail 1)", [_f(own[c]["params"]["mode"][mo], 2) if own[c] else "–" for c in FIT]))
        for v in ("5", "10", "20", "30", "50"):
            L.append(_row(f"speed curve at {v} km/h", [_f(own[c]["params"]["curve_S"][v], 2) if own[c] else "–" for c in FIT]))
        L.append("")

    oc = {c: _j(out, f"own_ctrl_{c}") for c in FIT}
    if any(oc.values()):
        L += ["## 2b. Each city on its own with its usual controls: are the curves alike?", "", "The US fit's controls (density, income, "
              "poverty, education, age), those the city has, standardised within the city; no vote shares. Speed first, then mode.", "",
              _head(cols)]
        L.append(_row("held-out R², no controls", [_f(own[c]["cv"]["r2"][c]) if own.get(c) else "–" for c in FIT]))
        L.append(_row("held-out R², usual controls", [_f(oc[c]["cv"]["r2"][c]) if oc[c] else "–" for c in FIT]))
        L.append(_row("held-out skill, usual controls", [_f(oc[c]["cv"]["skill"][c], 4) if oc[c] else "–" for c in FIT]))
        for h in ("5", "10", "20", "30"):
            L.append(_row(f"headway curve at {h} min", [_f(oc[c]["params"]["curve_H_10min20kmh"][h], 2) if oc[c] else "–" for c in FIT]))
        for w in ("200", "400", "800", "1200"):
            L.append(_row(f"walk curve at {w} m (10 min, 20 km/h)", [_f(oc[c]["params"]["curve_W_at_10min_20kmh"][w], 2) if oc[c] else "–" for c in FIT]))
        for v in ("5", "10", "20", "30", "50"):
            L.append(_row(f"speed curve at {v} km/h", [_f(oc[c]["params"]["curve_S"][v], 2) if oc[c] else "–" for c in FIT]))
        for mo in ("bus", "tram"):
            L.append(_row(f"mode factor {mo} (rail 1)", [_f(oc[c]["params"]["mode"][mo], 2) if oc[c] else "–" for c in FIT]))
        L.append(_row("eps", [_f(oc[c]["params"]["eps"], 4) if oc[c] else "–" for c in FIT]))
        names = sorted({k for c in FIT if oc[c] for k in oc[c]["coefficients"]})
        for k in names:
            L.append(_row(f"coefficient {k} (per sd)", [_f(oc[c]["coefficients"].get(k), 2) if oc[c] else "–" for c in FIT]))
        L.append("")
    tc = _j(out, "transfer_ctrl")
    if tc:
        L += ["Curves of one city's fit with controls predicting another: the target's level, dispersion and coefficients of its own usual "
              "controls fitted on its training folds (within-city 5-fold held-out R²; diagonal: the city's own held-out R²):", "", _head(cols)]
        for a_ in FIT:
            if a_ in tc:
                L.append(_row(NAMES[a_], [_f(tc[a_][b_]["r2"]) if b_ in tc[a_] else (_f(oc[a_]["cv"]["r2"][a_]) if oc.get(a_) else "–") for b_ in FIT]))
        L.append("")

    tr = _j(out, "transfer")
    if tr:
        L += ["## 3. Fitted in one city, predicting another", "", "Rows: where the curves come from; columns: the city predicted, with only its "
              "level (+ dispersion) refitted on its own units. Second table: level and slope (the service effect scaled per city).", ""]
        for key, title in (("level", "level refitted"), ("level_slope", "level and slope refitted")):
            L += [f"R², {title}:", "", _head(cols)]
            for a in ["us"] + FIT:
                if a in tr:
                    L.append(_row(NAMES[a], [_f(tr[a][b][key]["r2"]) if b in tr[a] else "(own)" for b in FIT]))
            L.append("")

    po = _j(out, "pooled")
    loco = {c: _j(out, f"loco_{c}") for c in FIT}
    if po or any(loco.values()):
        L += ["## 4. The five cities pooled (each its own level)", "", _head(cols + ["mean"])]
        if po:
            L.append(_row("pooled, within-city held-out R²", [_f(po["cv"]["r2"][c]) for c in FIT] + [_f(po["cv"]["r2_mean"])]))
            L.append(_row("pooled, within-city held-out skill", [_f(po["cv"]["skill"][c], 4) for c in FIT] + [_f(po["cv"]["mean"], 4)]))
        L.append(_row("left out (fitted on the other four), R², level", [_f(loco[c]["level"]["r2"]) if loco[c] else "–" for c in FIT] + [""]))
        L.append(_row("left out, R², level + slope", [_f(loco[c]["level_slope"]["r2"]) if loco[c] else "–" for c in FIT] + [""]))
        L.append("")

    ct = _j(out, "controls")
    if ct:
        L += ["## 5. Controls across cities", "", "On the pooled curves (frozen), within-city 5-fold held out. Vote shares are not used as a shared control (their meaning differs "
              "between countries). The treatments:", ""]
        L += [_head(cols + ["mean R²", "mean skill"])]
        labels = {"none": "no controls", "pooled_raw_one_level": "pooled standardisation, one level for all cities",
                  "pooled_raw": "pooled standardisation, city levels", "within_z": "standardised within each city, city levels",
                  "within_rank": "within-city ranks, city levels"}
        for k, r in ct["modes"].items():
            L.append(_row(labels.get(k, k), [_f(r["r2"][c]) for c in FIT] + [_f(r["r2_mean"]), _f(r["mean"], 4)]))
        L += ["", "Share of each control's variance that lies between the cities (η²; 1 = the control only separates the cities) and its "
              "coefficient: pooled standardisation with one level, with city levels, and standardised within each city:", "",
              "| control | cities with it | η² between cities | one level | city levels | within city |", "|---|---|---:|---:|---:|---:|"]
        co = ct["coefficients"]
        for c, e in sorted(ct["between_city_share"].items(), key=lambda x: -x[1]):
            L.append(f"| {c} | {', '.join(NAMES[x] for x in ct['coverage'][c])} | {e:.2f} | {_f(co['one_level'].get(c))} | "
                     f"{_f(co['city_levels'].get(c))} | {_f(co['within_z'].get(c))} |")
        L += ["", "Forward selection (within-city standardised, kept while the held-out skill gains ≥ 0.001):", ""]
        for s in ct["forward"]["steps"]:
            L.append(f"* + {s['added']}: mean skill {s['mean']:.4f} (gain {s['gain']:+.4f})")
        L += ["", f"Selected: {', '.join(ct['forward']['selected']) or 'none'}.", ""]

    fi = _j(out, "final")
    if fi:
        L += ["## 6. Final pooled fit with the selected controls", "", f"Controls (within-city standardised): {', '.join(fi['controls']) or 'none'}.",
              "", _head(cols + ["mean"])]
        L.append(_row("within-city held-out R²", [_f(fi["cv"]["r2"][c]) for c in FIT] + [_f(fi["cv"]["r2_mean"])]))
        L.append(_row("within-city held-out skill", [_f(fi["cv"]["skill"][c], 4) for c in FIT] + [_f(fi["cv"]["mean"], 4)]))
        L.append(_row("left out, R², level", [_f(fi["loco"][c]["level"]["r2"]) for c in FIT] + [""]))
        L.append(_row("left out, R², level + slope", [_f(fi["loco"][c]["level_slope"]["r2"]) for c in FIT] + [""]))
        p = fi["params"]
        L += ["", f"Curves: headway half value {p['h50_min']:.1f} min (slope {p['kh']:.2f}); walk half distance {p['w50_m']:.0f} m (slope "
              f"{p['kw']:.2f}, x (h / 10 min)^{p['c_h']:.2f} x (v / 20 km/h)^{p['c_v']:.2f}); mode factors bus {p['mode']['bus']:.2f}, tram "
              f"{p['mode']['tram']:.2f}, rail 1; eps {p['eps']:.4f}.", ""]

    sm = {"US final curves": (us or {}).get("small_us"), "map default score": (us or {}).get("small_default"),
          "pooled five": (po or {}).get("small"), "final (with controls)": (fi or {}).get("small")}
    if any(sm.values()):
        L += ["## 7. Small cities (7–30 units): predicted only", "", "After the city's level (slope 1): R² of the logit share; in brackets the rank "
              "correlation of the predicted service term with the share. The measures differ (see `flex/README.md`).", "",
              _head([NAMES[c] for c in SMALL])]
        for lab, r in sm.items():
            if r:
                L.append(_row(lab, [f"{_f(r[c]['r2_level'], 2)} ({_f(r[c]['spearman'], 2)})" for c in SMALL]))
        L.append(_row("units", [str(next(r for r in sm.values() if r)[c]["units"]) for c in SMALL]))
        L.append("")
    import re
    VAR = r"common(_slope)?(?:_kh([0-9.]+))?(?:_h(us))?(_tm)?(_sn)?(?:_cc([a-z]+))?"
    CC = {"b": "Boston", "s": "San Francisco", "t": "Toronto", "c": "Concepción", "g": "Guadalajara"}

    def _key(v):
        m = re.fullmatch(VAR, v)
        return (bool(m.group(1)), bool(m.group(3)), bool(m.group(4)), bool(m.group(5)), m.group(6) or "", float(m.group(2) or 0))

    def _lab(v):
        m = re.fullmatch(VAR, v)
        return ("one score" + (", city slopes" if m.group(1) else "") + (f", headway steepness held at {m.group(2)}" if m.group(2) else "")
                + (", the US headway curve" if m.group(3) else "")
                + (", tram halfway between bus and rail" if m.group(4) else "") + (", city slopes around 1" if m.group(5) else "")
                + (", curves from " + " / ".join(CC[x] for x in m.group(6)) if m.group(6) else ""))
    khs = sorted({m.group(0) for p in out.glob("common*.json")
                  if (m := re.match(VAR + r"(?=$|_cv$|_loco_)", p.stem))} - {"common", "common_slope"}, key=_key)
    vs = [v for v in ("common", "common_slope", *khs) if _j(out, f"{v}_cv") or _j(out, v) or any(_j(out, f"{v}_loco_{c}") for c in FIT)]
    if vs:
        oc = {c: _j(out, f"own_ctrl_{c}") for c in FIT}
        L += ["## 8. One score for every city", "", "The curves (headway, walk, speed, mode factors, eps) shared by the five cities; each city its "
              "own level and its own coefficients of its usual controls (outside the score). *slope*: also each city's own slope of the score. "
              "Held-out R² (within-city 5-fold); left out: curves from the other four, the city's level and control coefficients fitted on its "
              "training folds.", "", _head(cols + ["mean"])]
        L.append(_row("each city's own fit with controls (2b)", [_f(oc[c]["cv"]["r2"][c]) if oc[c] else "–" for c in FIT]
                      + [_f(sum(oc[c]["cv"]["r2"][c] for c in FIT) / 5) if all(oc.values()) else "–"]))
        for v in vs:
            lab = _lab(v)
            cv = _j(out, f"{v}_cv")
            if cv:
                L.append(_row(f"{lab}: pooled", [_f(cv["cv"]["r2"][c]) for c in FIT] + [_f(cv["cv"]["r2_mean"])]))
            lo = {c: _j(out, f"{v}_loco_{c}") for c in FIT}
            if any(lo.values()):
                ok = all(lo.values())
                L.append(_row(f"{lab}: left out", [_f(lo[c]["controls"]["r2"]) if lo[c] else "–" for c in FIT]
                              + [_f(sum(lo[c]["controls"]["r2"] for c in FIT) / 5) if ok else "–"]))
                L.append(_row(f"{lab}: left out, no controls", [_f(lo[c]["no_controls"]["r2"]) if lo[c] else "–" for c in FIT] + [""]))
        L.append("")
        for v in vs:
            fu = _j(out, v)
            if not fu:
                continue
            p = fu["params"]
            H, W, S = p["curve_H_10min20kmh"], p["curve_W_at_10min_20kmh"], p["curve_S"]
            L += [f"Curves ({_lab(v)}, all units): headway " +
                  ", ".join(f"{k} min {H[k]:.2f}" for k in ("5", "10", "20", "30")) + "; walk " +
                  ", ".join(f"{k} m {W[k]:.2f}" for k in ("200", "400", "800", "1200")) + "; speed " +
                  ", ".join(f"{k} km/h {S[k]:.2f}" for k in ("5", "10", "20", "30", "50")) +
                  f"; bus {p['mode']['bus']:.2f}, tram {p['mode']['tram']:.2f}, rail 1; eps {p['eps']:.4f}"
                  + (("; city slopes " + ", ".join(f"{NAMES[c]} {x:.2f}" for c, x in zip(FIT, p["slope"]))) if "slope" in v else "") + ".", ""]
            sm = fu.get("small")
            if sm:
                L += ["Small cities with this score (R² of the logit share after the level; rank correlation): " +
                      ", ".join(f"{NAMES[c]} {sm[c]['r2_level']:.2f} ({sm[c]['spearman']:.2f})" for c in SMALL) + ".", ""]
    f = Path(__file__).resolve().parent / "FIT_RESULTS.md"
    f.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {f}")
    return f
